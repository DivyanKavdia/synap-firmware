'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const source=fs.readFileSync(path.join(root,'firmware/shared/odyssey-sd-transfer.cpp'),'utf8');
const runtime=fs.readFileSync(path.join(root,'firmware/shared/runtime.cpp'),'utf8');
const caps=fs.readFileSync(path.join(root,'firmware/shared/module-capabilities.cpp'),'utf8');
const catalog=require('../devices/catalog.json');
const c3=catalog.devices.find(device=>device.id==='esp32c3-supermini-4m');

assert(c3.features.includes('sd'),'C3 must advertise SD support');
assert.equal(c3.protocols?.media,1,'catalogue keeps media-v1 as the compatibility floor');
assert.match(runtime,/namespace OdysseyTransfer/);
assert.match(caps,/p\[14\]=OdysseyTransfer::streamAvailable\(\)\?2:1/);
assert.match(caps,/p\[16\]=OdysseyTransfer::streamAvailable\(\)\?1:0/);
assert.match(caps,/ready\|=SYNAP_CAP_SD/);
assert.match(source,/odysseyRecording\.load\(\) \|\| streamingEnabled\.load\(\) \|\| otaBusy\(\)/);
assert.match(source,/case 7:\s*error=catalogue\(total\)/);
assert.match(source,/case 4:\s*error=readSelected\(request\.path,request\.offset,total,bytes,size\)/);
assert.match(source,/!strcmp\(requestedPath,"@catalogue"\)/);
assert.match(source,/safeWavPath\(requestedPath\)/);
assert.match(source,/transfer begin path=%s/);
assert.match(source,/New clients make every chunk self-describing/);
assert.match(source,/TRANSFER_STACK_BYTES=8192/,'C3 SD transfer needs an 8 KiB worker stack for FAT directory enumeration');
assert.match(source,/xTaskCreate\(worker,"odyssey-sd",TRANSFER_STACK_BYTES/);
assert.match(source,/case 17: error=removeFile\(request\.path\)/);
assert.match(source,/case 18:/);
assert.match(source,/\/synap\//);
assert.match(source,/opendir\(directoryPath\)/);
assert.match(source,/fopen\(full,"rb"\)/);
assert.match(source,/unlink\(full\)/);
assert.match(source,/OdysseySdGuard guard/);
assert.doesNotMatch(source,/\bSD\.|\bFile\b|format_if_empty/);
console.log('PASS: Odyssey C3 exposes VFS-backed SD catalogue, verified-delete endpoint and non-formatting clear action.');
