'use strict';
const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {prepare}=require('../tools/prepare-interactions.cjs');
const {patch:runtime}=require('../tools/patch-runtime-fixes.cjs');
const {patch:touch}=require('../tools/patch-touch-reliability.cjs');
const root=path.join(__dirname,'..');

test('TTP223 implements only 2s start, recording double-tap stop and 5s sleep/wake',()=>{
  const source=fs.readFileSync(path.join(root,'synap_esp32s3/synap_esp32s3.ino'),'utf8');
  const prepared=touch(runtime(prepare(source)));
  assert.match(prepared,/pinMode\(TOUCH_INPUT_PIN, INPUT\);/);
  assert.doesNotMatch(prepared,/pinMode\(TOUCH_INPUT_PIN, INPUT_PULLDOWN\);/);
  assert.match(prepared,/TOUCH_SLEEP_HOLD_MS = 5000/);
  assert.match(prepared,/TOUCH_START_HOLD_MS = 2000/);
  assert.match(prepared,/TOUCH_TAP_MAX_MS = 450/);
  assert.match(prepared,/TOUCH_STATE_LOCKOUT_MS = 650/);
  assert.match(prepared,/held>=TOUCH_START_HOLD_MS && held<TOUCH_SLEEP_HOLD_MS && connected/);
  assert.match(prepared,/touchFirstTapAt && uint32_t\(now-touchFirstTapAt\)<=TOUCH_DOUBLE_TAP_MS/);
  assert.match(prepared,/double tap while recording -> STOP/);
  assert.match(prepared,/first recording tap; waiting for second tap/);
  assert.match(prepared,/held>=TOUCH_SLEEP_HOLD_MS/);
  assert.match(prepared,/sleepAfterStop=true[\s\S]*?CMD_STOP/,'5s hold during recording must stop cleanly before sleep');
  assert.match(prepared,/esp_sleep_get_wakeup_cause\(\)/);
  assert.match(prepared,/wake detected; hold for 5 seconds to stay awake/);
  assert.match(prepared,/wake hold too short; returning to deep sleep/);
  assert.match(prepared,/armTouchWakeAndSleep\(\)/);
  const poll=prepared.slice(prepared.indexOf('void pollTouchControl() {'),prepared.indexOf('\n}\n',prepared.indexOf('void pollTouchControl() {'))+3);
  assert.doesNotMatch(poll,/publishRememberEvent/,'touch must no longer expose Remember This');
  assert.doesNotMatch(poll,/deliberate stop tap|TOUCH_STOP_MIN_MS|TOUCH_STOP_MAX_MS/,'single-tap stop path must be gone');
});
